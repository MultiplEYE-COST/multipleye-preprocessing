"""Codebook fields for the dataset view."""

from __future__ import annotations

from preprocessing.metadata.schema import CodebookField

__all__ = ["FIELDS"]


def _field(
    path: str,
    feature_label: str,
    description: str,
    data_type: str,
    source_section: str,
    semantic_category: str,
    *,
    unit: str = "",
    allowed_values: str = "",
    notes: str = "",
) -> CodebookField:
    """Build a dataset field from its YAML path."""
    variable_name = path.rsplit(".", 1)[-1].removesuffix("[]")
    return CodebookField(
        variable_id=f"dataset.{path.replace('[]', '')}",
        view_level="dataset",
        variable_name=variable_name,
        feature_label=feature_label,
        description=description,
        data_type=data_type,
        unit=unit,
        allowed_values=allowed_values,
        source_section=source_section,
        pipeline_field=path,
        yaml_path=path,
        semantic_category=semantic_category,
        aggregation_behavior="not_applicable",
        notes=notes,
    )


