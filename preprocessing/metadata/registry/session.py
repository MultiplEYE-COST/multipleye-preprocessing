__all__ = ["FIELDS"]


def _field(
    path: str,
    feature_label: str,
    description: str,
    data_type: str,
    source_section: str,
    semantic_category: str,
    *,
    unit: str = "",
    allowed_values: str = "",
    notes: str = "",
) -> CodebookField:
    """Build a session field from its YAML path."""
    variable_name = path.rsplit(".", 1)[-1].removesuffix("[]")
    return CodebookField(
        variable_id=f"session.{path.replace('[]', '')}",
        view_level="session",
        variable_name=variable_name,
        feature_label=feature_label,
        description=description,
        data_type=data_type,
        unit=unit,
        allowed_values=allowed_values,
        source_section=source_section,
        pipeline_field=path,
        yaml_path=path,
        semantic_category=semantic_category,
        aggregation_behavior="not_applicable",
        notes=notes,
    )


