__all__ = ["FIELDS"]


def _field(
    path: str,
    feature_label: str,
    description: str,
    data_type: str,
    source_section: str,
    semantic_category: str,
    *,
    unit: str = "",
    allowed_values: str = "",
    aggregation_base_level: str = "",
    aggregation_method: str = "",
    aggregation_input: str = "",
    aggregation_behavior: str = "not_applicable",
    notes: str = "",
) -> CodebookField:
    """Build an item field from its path below ``items[]``."""
    variable_name = path.rsplit(".", 1)[-1].removesuffix("[]")
    return CodebookField(
        variable_id=f"item.{path.replace('[]', '')}",
        view_level="item",
        variable_name=variable_name,
        feature_label=feature_label,
        description=description,
        data_type=data_type,
        unit=unit,
        allowed_values=allowed_values,
        source_section=source_section,
        pipeline_field=path,
        yaml_path=f"items[].{path}",
        semantic_category=semantic_category,
        aggregation_base_level=aggregation_base_level,
        aggregation_method=aggregation_method,
        aggregation_input=aggregation_input,
        aggregation_behavior=aggregation_behavior,
        notes=notes,
    )


